"""Tampered system files: installed files that no longer match their package, and
executables in system directories that no package owns."""
from __future__ import annotations

import grp
import json
import os
import pwd
import re
import stat
import time
from collections import defaultdict

from .. import config
from ..findings import Finding
from .common import priv, sh

CAT = "packages"
CRITICAL_DIRS = ("/usr/bin/", "/usr/sbin/", "/usr/lib/", "/usr/lib64/", "/usr/libexec/")
UNOWNED_DIRS = ("/usr/bin", "/usr/lib/systemd/system", "/usr/lib/systemd/user")
# Generated at install time by hooks; not package-owned, never suspicious.
GENERATED_OK = ("/usr/lib/systemd/system/multi-user.target.wants", "/usr/lib/systemd/system/local-fs.target.wants")


def _cache_get(key: str, max_age: float):
    try:
        store = json.loads(config.CACHE_PATH.read_text())
        ent = store.get(key)
        if ent and time.time() - ent["t"] < max_age:
            return ent["v"], ent["t"]
    except (OSError, ValueError, KeyError):
        pass
    return None, None


def _cache_put(key: str, value) -> None:
    try:
        store = json.loads(config.CACHE_PATH.read_text())
    except (OSError, ValueError):
        store = {}
    store[key] = {"t": time.time(), "v": value}
    config.CACHE_PATH.parent.mkdir(parents=True, exist_ok=True)
    tmp = config.CACHE_PATH.with_suffix(".tmp")
    tmp.write_text(json.dumps(store))
    tmp.replace(config.CACHE_PATH)


# Files that distro tooling rewrites after install on purpose: (regex, why).
KNOWN_BENIGN = [
    (r"^/usr/lib/jvm/default(-runtime)?$", "archlinux-java repoints this symlink when the default Java changes"),
    (r"^/usr/lib/plymouth/plymouth-update-initrd$", "CachyOS patches this script after each plymouth update"),
    (r"^/usr/lib/vlc/plugins/plugins\.dat$", "VLC rebuilds its plugin cache after updates (vlc-cache-gen)"),
    (r"^/usr/lib/gdk-pixbuf-2\.0/.*/loaders\.cache$", "regenerated by the gdk-pixbuf hook"),
    (r"^/usr/lib/gio/modules/giomodule\.cache$", "regenerated by the gio hook"),
    (r"^/usr/lib/gtk-[234]\.0/.*/immodules\.cache$", "regenerated by the gtk hook"),
    (r"^/usr/share/glib-2\.0/schemas/gschemas\.compiled$", "regenerated by the glib schema hook"),
    (r"^/usr/share/icons/.*/icon-theme\.cache$", "regenerated by the icon-cache hook"),
    (r"^/usr/share/mime/", "regenerated by update-mime-database"),
    (r"^/usr/lib/locale/locale-archive$", "regenerated by locale-gen"),
    (r"^/usr/lib/modules/.*/modules\.", "regenerated by depmod"),
    (r"^/usr/share/info/dir$", "regenerated by install-info"),
    (r"^/usr/lib/ghc-.*/package\.conf\.d/package\.cache", "regenerated by ghc-pkg"),
    (r"^/usr/lib/python3\.\d+/.*__pycache__/", "Python bytecode rebuilt on import"),
]
_BENIGN_RX = [(re.compile(r), why) for r, why in KNOWN_BENIGN]

# Files that ship with special permissions (setuid/setgid) applied by the package's
# install script after pacman records the file, so -Qkk always reports a mismatch.
# Treated as expected ONLY while the file has exactly this mode and ownership;
# anything looser (world-writable, another owner) is still flagged.
#   path: (mode, owner, group, why)
KNOWN_SPECIAL_PERMS = {
    "/usr/bin/mullvad-exclude": (0o4755, "root", "root",
        "setuid root, set by Mullvad's install script for split tunnelling"),
    "/usr/lib/utempter/utempter": (0o2755, "root", "utmp",
        "setgid utmp so terminals can record logins; the utmp group ID differs from the package's record"),
}


def special_perms_reason(path: str) -> str | None:
    """Why a permissions/ownership mismatch on `path` is expected, or None."""
    want = KNOWN_SPECIAL_PERMS.get(path)
    if not want:
        return None
    mode, owner, group, why = want
    try:
        st = os.lstat(path)
        if (stat.S_IMODE(st.st_mode) == mode and pwd.getpwuid(st.st_uid).pw_name == owner
                and grp.getgrgid(st.st_gid).gr_name == group):
            return why
    except (OSError, KeyError):
        pass
    return None


def benign_reason(path: str, extra: list[str] | None = None) -> str | None:
    for rx, why in _BENIGN_RX:
        if rx.search(path):
            return why
    for pat in extra or []:
        if re.search(pat, path):
            return "ignored in settings (integrity_ignore)"
    return None


def classify(issues: list[dict], extra_ignore: list[str] | None = None) -> list[Finding]:
    """Turn pacman -Qkk discrepancies into findings. Exposed for tests."""
    content, perms, missing, other = defaultdict(set), defaultdict(set), defaultdict(set), defaultdict(set)
    expected: dict[str, str] = {}
    for it in issues:
        path, pkg, reason = it["path"], it["pkg"], it["reason"]
        why = benign_reason(path, extra_ignore)
        if why:
            expected[path] = f"{pkg}: {why}"
            continue
        if "checksum mismatch" in reason or "Size mismatch" in reason or "Symlink path mismatch" in reason \
                or "File type mismatch" in reason:
            content[path].add(pkg)
        elif any(w in reason for w in ("Permissions mismatch", "UID mismatch", "GID mismatch")):
            why = special_perms_reason(path)
            if why:
                expected[path] = f"{pkg}: {why}"
            else:
                perms[path].add(f"{pkg}: {reason}")
        elif "No such file" in reason:
            missing[path].add(pkg)
        else:
            other[path].add(f"{pkg}: {reason}")

    out: list[Finding] = []
    crit = sorted(p for p in content if p.startswith(CRITICAL_DIRS))
    rest = sorted(p for p in content if not p.startswith(CRITICAL_DIRS))
    if crit:
        pkgs = sorted({pk for p in crit for pk in content[p]})
        out.append(Finding(CAT, "high", f"{len(crit)} system programs or libraries differ from their package",
                           "These binaries/libraries no longer match what the package installed. A modified "
                           "sudo, sshd or libc is how rootkits hide. Reinstalling restores the originals; if "
                           "you didn't patch them yourself, treat this machine as suspect.\n\n"
                           + "\n".join(f"  {p}  ({', '.join(sorted(content[p]))})" for p in crit[:40]),
                           fix=f"sudo pacman -S {' '.join(pkgs[:20])}"))
    if rest:
        out.append(Finding(CAT, "low", f"{len(rest)} packaged data files were modified",
                           "Outside the program directories — usually harmless (edited themes, docs, "
                           "app-modified resources).\n\n"
                           + "\n".join(f"  {p}  ({', '.join(sorted(content[p]))})" for p in rest[:40])))
    if perms:
        out.append(Finding(CAT, "medium", f"{len(perms)} packaged files have changed ownership or permissions",
                           "A binary made world-writable or given to another user can be swapped out later.\n\n"
                           + "\n".join(f"  {p}  ({'; '.join(sorted(v))})" for p, v in sorted(perms.items())[:40])))
    if missing:
        out.append(Finding(CAT, "info", f"{len(missing)} packaged files are missing",
                           "Usually deleted docs or locales. Reinstall the package if something misbehaves.\n\n"
                           + "\n".join(f"  {p}" for p in sorted(missing)[:25])))
    if other:
        out.append(Finding(CAT, "info", f"{len(other)} other package-file discrepancies",
                           "\n".join(f"  {p}  ({'; '.join(sorted(v))})" for p, v in sorted(other.items())[:25])))
    if not any(f.severity in ("low", "medium", "high") for f in out):
        out.insert(0, Finding(CAT, "ok", "All installed program files match their packages"))
    if expected:
        out.append(Finding(CAT, "info", f"{len(expected)} files changed by system tools on purpose",
                           "These differ from the package because a distro hook or tool rewrites them after install. "
                           "Not a sign of tampering.\n\n" + "\n".join(f"  {p}  ({w})" for p, w in sorted(expected.items())[:40])))
    return out


def tampered(cfg: dict) -> list[Finding]:
    max_age = float(cfg.get("integrity_every_hours", 24)) * 3600
    cached, t = _cache_get("integrity", max_age)
    if cached is None:
        data = priv("integrity", timeout=1900)
        if not isinstance(data, dict) or "issues" not in data:
            return [Finding(CAT, "info", "System file integrity not checked",
                            "The root helper isn't set up, or pacman -Qkk failed or timed out.",
                            fix=config.helper_setup())]
        cached, t = data["issues"], time.time()
        _cache_put("integrity", cached)
    findings = classify(cached, cfg.get("integrity_ignore", []))
    when = time.strftime("%Y-%m-%d %H:%M", time.localtime(t))
    for f in findings:
        f.detail = (f.detail + "\n\n" if f.detail else "") + f"(verified {when}; re-checked every {cfg.get('integrity_every_hours', 24)} h)"
    return findings


def unowned(cfg: dict) -> list[Finding]:
    owned_txt = sh(["pacman", "-Qlq"], timeout=120)
    if owned_txt is None:
        return []
    owned = set(p.rstrip("/") for p in owned_txt.splitlines())
    strays = []
    for d in UNOWNED_DIRS:
        try:
            names = os.listdir(d)
        except OSError:
            continue
        for n in names:
            full = os.path.join(d, n)
            if full in owned or full.startswith(GENERATED_OK):
                continue
            # /usr/sbin and /bin are symlinks to /usr/bin on Arch; pacman may record either spelling
            alt = full.replace("/usr/bin/", "/usr/sbin/")
            if alt in owned:
                continue
            if os.path.isdir(full):
                continue
            strays.append(full)
    if not strays:
        return [Finding(CAT, "ok", "Every program in /usr/bin belongs to a package")]
    return [Finding(CAT, "medium", f"{len(strays)} files in system directories aren't owned by any package",
                    "Installed outside pacman (make install, pip --break-system-packages, curl | sh installers) "
                    "or planted. Check you recognise each one; `pacman -Qo <file>` confirms nothing owns it.\n\n"
                    + "\n".join(f"  {s}" for s in sorted(strays)[:50]))]
